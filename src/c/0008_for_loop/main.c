// for loop

#include <stdio.h> // printf

int main()
{
    for (int i = 1; i <= 100; i++)
    {
        printf("%d ", i);
        printf("\n");
    }

    printf("\nPress Enter to Exit");

    // wait for user to press Enter
    getchar();

    return 0;
}

