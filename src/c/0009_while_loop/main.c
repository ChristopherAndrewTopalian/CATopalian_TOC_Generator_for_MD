// whileLoop

#include <stdio.h> // printf

int main()
{
    int i = 0; // initialize the counter

    while (i < 100)
    {
        printf("%d ", i);
        i++; // increment counter
    }

    printf("\n"); // print new line after loop

    printf("\nPress Enter to exit");

    getchar(); // wait for user input

    return 0;
}

